package engine

import (
	"context"
	"fmt"
	"strings"

	"github.com/tmc/langchaingo/llms"
	"github.com/tmc/langchaingo/llms/ollama"
	"go.opentelemetry.io/otel"
)

// Generator handles the interaction with an LLM to answer questions based on context
type Generator struct {
	client *ollama.LLM
}

// NewGenerator initializes a generator with a specific Ollama model
func NewGenerator(model string) (*Generator, error) {
	llm, err := ollama.New(ollama.WithModel(model))
	if err != nil {
		return nil, fmt.Errorf("failed to initialize ollama generator: %w", err)
	}
	return &Generator{client: llm}, nil
}

// GenerateAnswer takes a question and retrieved code context to produce a response
func (g *Generator) GenerateAnswer(ctx context.Context, question string, contextChunks []VectorizedChunk) (string, error) {
	tracer := otel.Tracer("engine")
	ctx, span := tracer.Start(ctx, "GenerateAnswer")
	defer span.End()

	// 1. Build the prompt with context
	var contextBuilder strings.Builder
	for i, chunk := range contextChunks {
		contextBuilder.WriteString(fmt.Sprintf("--- File: %s ---\n%s\n\n", chunk.FilePath, chunk.Content))
		if i >= 4 { // Limit context to top 5 chunks for window efficiency
			break
		}
	}

	systemPrompt := "You are an expert software engineer. Answer the user's question using ONLY the provided code snippets. If the answer isn't in the code, say you don't know."
	fullPrompt := fmt.Sprintf("Context:\n%s\n\nQuestion: %s\n\nAnswer:", contextBuilder.String(), question)

	// 2. Call the LLM
	content := []llms.MessageContent{
		llms.TextParts(llms.ChatMessageTypeSystem, systemPrompt),
		llms.TextParts(llms.ChatMessageTypeHuman, fullPrompt),
	}

	resp, err := g.client.GenerateContent(ctx, content)
	if err != nil {
		return "", fmt.Errorf("llm generation failed: %w", err)
	}

	if len(resp.Choices) == 0 {
		return "No response generated by LLM", nil
	}

	return resp.Choices[0].Content, nil
}
